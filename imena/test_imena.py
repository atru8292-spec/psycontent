# Проверка службы imena без HTTP (26.11.2026): python test_imena.py [модель]. Запускать в venv службы.
# Имена клиентов должны находиться, известные люди, герои и обычные слова нет.
import sys
import spacy, pymorphy3
import app

app.nlp = spacy.load(sys.argv[1] if len(sys.argv) > 1 else 'ru_core_news_md', exclude=['parser', 'lemmatizer', 'attribute_ruler'])
app.morph = pymorphy3.MorphAnalyzer()
app.ODNO, app.PARY = app.load_izvestnye()

NADO = [  # (фраза, имена, которые должны найтись)
    ('Вчера Снежана сказала, что муж опять не пришел.', {'Снежана'}),
    ('Ко мне ходит женщина, у нее сын Ярик, ему семь.', {'Ярик'}),
    ('На сессии Ева и Лев поругались из-за денег.', {'Ева', 'Лев'}),
    ('Сегодня Аглая плакала, мама сравнила ее с сестрой.', {'Аглая'}),
    ('Тёма, сын клиентки, перестал разговаривать.', {'Тёма'}),
    ('С Таисией мы разбирали, почему она выбирает холодных мужчин.', {'Таисией'}),
    ('Мне написала Айгерим, что впервые выспалась.', {'Айгерим'}),
    ('Сашка, младший брат клиента, снова в больнице.', {'Сашка'}),
    ('Вера пришла и молчала весь час.', {'Вера'}),
    ('Любовь Ивановна, моя клиентка, плакала.', {'Любовь', 'Ивановна'}),
    ('Давайте представим, у нас есть Андрей и его жена Катя.', {'Андрей', 'Катя'}),
]
NELZYA = [  # фразы, где ничего закрывать нельзя
    'Как говорил Зигмунд Фрейд, все из детства.',
    'Лев Толстой писал о счастливых семьях.',
    'Помните Колма из «Банши Инишерина»?',
    'Вера в себя появляется не сразу.',
    'Страх и Стыд ходят парой.',
    'Слайд 2: Я. Личность.',
    'Лень это не порок, а сигнал.',
    'Джокер смеется, когда больно.',
]
bad = 0
for t, want in NADO:
    got = {x['t'] for x in app.najti(t)}
    if not want <= got:
        bad += 1; print('НЕ НАШЛОСЬ', want - got, 'в:', t)
for t in NELZYA:
    got = [x['t'] for x in app.najti(t)]
    if got:
        bad += 1; print('ЛИШНЕЕ', got, 'в:', t)
print('test_imena:', 'все проверки прошли' if not bad else f'ошибок {bad}')
sys.exit(1 if bad else 0)
