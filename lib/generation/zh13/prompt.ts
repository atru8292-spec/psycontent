const kusokBlok = (lead: string, kusok: string) => `${lead}\n<живой кусок>\n${kusok}\n</живой кусок>\nЕго слова и мысли не бери, только то, как он звучит.`

function hvost(z: Zadanie13): string {
  const drugie = FORMATY.filter(x => x.kod !== z.f.kod).map(x => `${x.kod}: ${x.imya}`).join('\n')
  const kak = z.f.vid !== 'reels' ? '' : z.f.vyvod === 'ekran'
    ? 'После подписи блок «Как снять:»: надписи по порядку, каждая строкой «- Экран 1, 3 секунды: что написать», и одной строкой, на каком фоне снять и как наложить надписи в CapCut или в редакторе Инстаграма.'
    : [
      'После подписи блок «Как снять:»: 3-6 коротких шагов, каждый строкой с «- ». Пиши так, как подруга объясняет, что сделать, а не как сценарий для съемочной группы. Каждый шаг начинается с действия: «Поставь телефон на уровне глаз, сядь у окна», «Сними часть, где ты отвечаешь», «Вторую часть сними как клиент», «Наложи надпись: ...».',
      'Без слов «план», «кадр», «футаж», «ракурс», без света и музыки. Если нужен монтаж (два окна, смена ролей, надписи), одной строкой, как это сделать в CapCut или в редакторе Инстаграма.',
    ].join(' ')
  return [
    kak,
    `В самом конце ответа, отдельно от текста, блок «Подойдет еще:»: три других формата из списка, которые лучше всего подходят под ${z.mysl ? 'эту мысль' : 'эту тему'}, каждый строкой «- код: почему подходит» (почему одной короткой фразой до 10 слов, про эту ${z.mysl ? 'мысль' : 'тему'}, например «тут есть живой диалог с клиентом»).\n${drugie}`,
  ].filter(Boolean).join('\n\n')
}

export function prompt13(a: Avtor13, z: Zadanie13): { system: string; user: string; pary: string[] } {
  const f = z.f
  const mn = f.vid === 'reels' ? 'рилсы' : f.vid === 'carousel' ? 'карусели' : 'посты'
  const teksty = z.obrazcy.map((x, i) => {
    const shapka = x.istochnik === 'razbor104' || x.id.startsWith('r104:') ? 'разбор живого рилса: как он устроен и что в нем говорят' : (x.format === 'reels' ? 'рилс' : x.format === 'carousel' ? 'карусель' : 'пост')
    return `<Образец ${i + 1} (${shapka})>\n${x.tekst}\n</Образец ${i + 1}>`
  }).join('\n\n')
  const kak = f.kak.replace('{huk}', z.huk)
  const chto = f.vid === 'reels' ? `рилс: ${kak}` : f.vid === 'carousel' ? `карусель: ${kak}` : `пост: ${kak}`
  const chistTema = (s: string) => s.replace(/[«»]/g, '')
  const zadacha = z.mysl
    ? [
      `Сделай свой ${chto}.`,
      `Мысль автора, его словами: «${z.mysl}».`,
      'Текст пишется из этой мысли: ее смысл главный, не меняй его и не дописывай своих выводов, которых в ней нет. Разворачивай ее живыми примерами и деталями.',
      z.situaciya ? `Если к мысли подходит ситуация «${z.situaciya}», можно от нее оттолкнуться; не подходит, не бери.` : '',
    ].filter(Boolean).join(' ')
    : `Сделай свой ${chto}. Тема: ${chistTema(z.tema || '')}.${z.situaciya ? ` Ситуация, от которой можно оттолкнуться: ${z.situaciya}.` : ''}`
  const mat = a.mat === 'mozhno' ? 'Мат можно.' : a.mat === 'tochechno' ? 'Мат можно точечно, со звездочкой в середине слова.' : 'Без мата.'
  const opora = z.mysl ? `${z.opora} (бери это, только если подходит к мысли)` : z.opora
  const ktoStr = kto(a)
  const psiholog = `Ты психолог, ${a.rod === 'm' ? 'мужчина' : 'женщина'}.${ktoStr ? ` Твои клиенты: ${ktoStr}.` : ''} Как ты смотришь на людей: ${opora}. Голос: ${a.golos}. К зрителю ${a.vy ? 'на «вы»' : 'на «ты»'}. ${mat}`

  // рилсы R1 (оценки Арины 19.11: «выложила бы» 4 из 5 против 2 из 5 у Р3 с «как сказал бы вслух»)
  const ritm = kusokBlok(RITM[f.vid], z.kusok)
  const podpisi = f.vid === 'post' ? '' : `Так звучат живые подписи под роликами и каруселями:\n${PODPISI.map(x => `- ${x}`).join('\n')}\nПодпись не начинай с «Можно» и «Иногда».`
  // «Подожди,» в начале переносился из живых образцов неудобных вопросов во все тексты формата (zh11, zh13)
  const podozhdi = f.kod === 'voprosy' ? 'Первый вопрос не начинай со слова «Подожди».' : ''
  const rod = /женщин/i.test(a.gender || '') ? '' : 'Твои читатели и мужчины, и женщины: к читателю пиши без рода (не «сама», не «устала», не «бездельница»).'

  // пары «было / живо» случайно из пула формата (z.seedPar только для тестов)
  const pary = paryDlya(f.kod, f.vid, z.seedPar)
  const user = [
    `Вот как делают такие ${mn} живые психологи-блогеры.`,
    teksty,
    zadacha,
    psiholog,
    [ritm, podpisi, podozhdi, rod].filter(Boolean).join('\n\n'),
    // понятность (ZH13-PRAVKI-ARINY.md): одна строка дословно и 3-4 пары «было / живо» под формат
    `${PONYATNO}\n\n${paryBlok(pary)}`,
    'Образцы нужны, чтобы понять устройство. Фразы, истории и примеры из них не бери, все свое.',
    VYVOD[f.vyvod],
    hvost(z),
    `Нельзя: ставить диагнозы, обещать вылечить, ссылаться на исследования, цифры и цитаты, которых ты не знаешь точно. Фактов о твоей жизни здесь нет, поэтому о своей жизни от первого лица как о факте не пиши.${f.kod === 'voprosy' ? '' : ' Не заканчивай текст вопросом к подписчикам.'} Буква «е» вместо «ё», без длинных тире.`,
  ].join('\n\n')
  return { system: 'Ты психолог и ведешь свой блог. Пишешь так, как пишут живые люди, своим голосом. Ответ: только сам текст в нужном виде, без пояснений.', user, pary: pary.map(p => p.zhivo.slice(0, 40)) }
}
