const imyaPodhoda = (a: string) => {
  const s = a.trim().toLowerCase()
  if (/кпт|когнитив/.test(s)) return 'КПТ'
  if (/гештальт/.test(s)) return 'Гештальт'
  if (/act|акт/.test(s)) return 'ACT'
  if (/психоанал|психодинам/.test(s)) return 'Психоанализ'
  if (/схем/.test(s)) return 'Схема-терапия'
  if (/эфт|эмоционально-фокус/.test(s)) return 'ЭФТ'
  if (/emdr|дпдг/.test(s)) return 'EMDR'
  if (/нарратив/.test(s)) return 'Нарративная терапия'
  if (/телесн/.test(s)) return 'Телесно-ориентированная'
  if (/экзистенц/.test(s)) return 'Экзистенциальный'
  if (/арт/.test(s)) return 'Арт-терапия'
  return 'Интегративный'
}

// опоры психолога: несколько подходов по кругу (первая опора первого подхода, первая второго...)
export function oporyPsihologa(approaches: unknown): string[] {
  const list = (Array.isArray(approaches) ? approaches : String(approaches || '').split(','))
    .map(x => String(x || '')).filter(x => x.trim())
  const kody = [...new Set((list.length ? list : ['Интегративный']).map(imyaPodhoda))]
  const po = kody.map(k => OPORY[k])
  const out: string[] = []
  for (let i = 0; i < 10; i++) for (const x of po) if (x[i]) out.push(x[i])
  return out
}

// опора текста: по кругу с номера n, не та же, что в последних трех текстах психолога
export function vybratOporu(opory: string[], n: number, poslednie: string[]): string {
  for (let i = 0; i < opory.length; i++) {
    const o = opory[(n * 7 + i) % opory.length]
    if (!poslednie.slice(0, 3).includes(o)) return o
  }
  return opory[n % opory.length]
}
