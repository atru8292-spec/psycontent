// экспериментов zh5): вычистка служебных тегов промпта и поиск «не X, а Y». Скопированы сюда, чтобы не менять общий
// text-guard.ts и не трогать поведение старого генератора zh+h7. Источник: feat/zh5d lib/generation/text-guard.ts.
