// Два примера под формат: сначала по смыслу, потом остальные; с матом только если мат разрешен.
// Сдвиг по числу материалов, чтобы примеры менялись от ролика к ролику.
export function pickExamples(format: FormatCode, intent: string, opts: { allowMat: boolean; rotation?: number; count?: number }): LiveExample[] {
  const ok = (e: LiveExample) => opts.allowMat || !e.mat
  let pool = LIVE_EXAMPLES.filter(e => e.format === format && ok(e))
  // мало своих примеров: добираем монологами (тоже живая речь в камеру)
  if (pool.length < (opts.count ?? 2) && format !== 'reels_monolog' && ['reels_otvet', 'reels_istoriya', 'reels_poslanie', 'reels_malysh'].includes(format)) {
    pool = [...pool, ...LIVE_EXAMPLES.filter(e => e.format === 'reels_monolog' && ok(e))]
  }
  if (!pool.length) return []
  const n = Math.min(opts.count ?? 2, pool.length)
  const byIntent = pool.filter(e => e.intents.includes(intent))
  const rest = pool.filter(e => !e.intents.includes(intent))
  const rot = (a: LiveExample[]) => {
    if (!a.length) return a
    const k = (opts.rotation || 0) % a.length
    return [...a.slice(k), ...a.slice(0, k)]
  }
  // один пример по смыслу (если есть) и один другой, чтобы модель видела разные ходы
  const first = rot(byIntent).slice(0, 1)
  const others = rot([...byIntent, ...rest]).filter(e => !first.includes(e))
  return [...first, ...others].slice(0, n)
}

export function examplesText(list: LiveExample[]): string {
  return list.map((e, i) => `<пример ${i + 1}>\nКак устроено: ${e.device}\n${e.text}\n</пример ${i + 1}>`).join('\n\n')
}
