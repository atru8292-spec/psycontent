export function fill(t: string, data: Record<string, string>): string {
  return t.replace(/\{([a-z]+)\}/g, (_, k) => (data[k] ?? ''))
}

// способ оплаты в тексте письма: « с карты •• 4242», « через СБП» или пусто (другого способа или нет в базе)
// причина в письме о неудачном списании: для СБП своя фраза (решение Арины 17.11), для карты и без способа прежняя
export function whyFailed(method?: string): string {
  return method === ' через СБП' ? 'Чаще всего на счете не хватило денег или банк временно не отвечает.' : 'Чаще всего на карте не хватило денег или у нее закончился срок.'
}

export function methodPhrase(type?: string | null, last4?: string | null): string {
  if (type === 'bank_card' && last4 && /^\d{4}$/.test(last4)) return ` с карты •• ${last4}`
  if (type === 'sbp') return ' через СБП'
  return ''
}
