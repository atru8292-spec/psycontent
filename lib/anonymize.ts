const ADJ_FORMS: Record<string, string[]> = { 'ий': ['ий', 'его', 'ему', 'им', 'ем'], 'ый': ['ый', 'ого', 'ому', 'ым', 'ом'], 'ой': ['ой', 'ого', 'ому', 'ым', 'ом'] }
// Падежи прилагательного: после г, к, х окончание твердое (Великий: Великого, Великом; Нижний: Нижнего, Нижнем)
function adjForms(adj: string): string[] {
  const end = adj.slice(-2), stem = adj.slice(0, -2)
  const af = end === 'ий' && /[гкх]$/.test(stem) ? ['ий', 'ого', 'ому', 'им', 'ом'] : ADJ_FORMS[end]
  return af ? af.map(e => stem + e) : [adj]
}
// Падежи одного слова-существительного (с запасом: лишняя форма вреда не делает)
function wordForms(w: string): string[] {
  const base = w.slice(0, -1), last = w.slice(-1)
  const soft = /[гкхжшчщц]$/.test(base)
  if (last === 'а') return [w, base + (soft ? 'и' : 'ы'), base + 'е', base + 'у', base + 'ой', base + 'ою']
  if (last === 'я') return [w, base + 'и', base + 'е', base + 'ю', base + 'ей']
  if (last === 'ь') return [w, base + 'и', base + 'ью', base + 'я', base + 'ю', base + 'ем', base + 'е']
  if (last === 'о' || last === 'е') return [w, base + 'а', base + 'у', base + 'ом', base + 'е']
  if (last === 'й') return [w, base + 'я', base + 'ю', base + 'ем', base + 'е']
  if (/[уиюэы]/.test(last)) return [w]
  return [w, w + 'а', w + 'у', w + 'ом', w + 'е']
}
function cityForms(city: string): string[] {
  if (COMPOUND_FORMS[city]) return COMPOUND_FORMS[city]
  if (FIXED_CITIES.has(city)) return [city]
  const sp = city.split(' ')
  if (sp.length === 2) {
    const [adj, noun] = sp
    return adjForms(adj).flatMap(a => wordForms(noun).map(n => `${a} ${n}`))
  }
  // Ростов-на-Дону, Комсомольск-на-Амуре: склоняется первая часть
  const na = city.match(/^([^-]+)(-на-.+)$/)
  if (na) return wordForms(na[1]).map(f => f + na[2])
  // Петропавловск-Камчатский, Каменск-Уральский: первая часть и прилагательное
  const adjTail = city.match(/^([^-]+)-([А-ЯЁ][а-яё]+(?:ий|ый))$/)
  if (adjTail) return wordForms(adjTail[1]).flatMap(f => adjForms(adjTail[2]).map(a => `${f}-${a}`))
  // Санкт-Петербург, Нур-Султан, Улан-Удэ, Южно-Сахалинск: склоняется последняя часть
  const dash = city.lastIndexOf('-')
  if (dash > 0) return wordForms(city.slice(dash + 1)).map(f => city.slice(0, dash + 1) + f)
  return wordForms(city)
}
