function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}
function nameStem(n: string): string {
  const s = n.replace(/[аяйь]$/i, '')
  return s.length >= 3 ? s : n
}
const NAME_STEMS = Array.from(new Set(RU_NAMES.map(nameStem)))
  .filter(s => s.length >= 3)
  .sort((a, b) => b.length - a.length)

// В JS \b не работает с кириллицей — границы задаём явно.
const NL = 'А-Яа-яЁёA-Za-z0-9_'
const CAPWORD = '[А-ЯЁ][а-яё]+'

// Слой 3: имя из словаря + опц. отчество/фамилия (до 2 слов с заглавной следом).
const NAME_RE = new RegExp(
  '(?<![' + NL + '])(' + NAME_STEMS.map(escapeRe).join('|') + ')[а-яё]{0,3}(?:[ \\t]+' + CAPWORD + '){0,2}(?![' + NL + '])',
  'g'
)

// Слой 2: маркеры контекста. После них слово(а) с заглавной — имя.
const MARKERS = [
  'меня зовут','зовут её','зовут его','зовут','по имени','имя',
  'клиентка','клиента','клиентки','клиенту','клиент','клиенткой',
  'пациентка','пациента','пациент','пациентку',
  'обратилась ко мне','обратился ко мне','обратилась','обратился','обращается',
  'пришла ко мне','пришёл ко мне','пришел ко мне','пришла','пришёл','пришел',
  'записалась','записался','познакомилась с','познакомился с',
]
// Маркеры — в обоих регистрах (нижний мид-предложения и Заглавный в начале), но
// БЕЗ флага 'i', иначе требование «слово с заглавной» в группе перестаёт работать.
const MARKERS_CASED = MARKERS.flatMap(m => [m, m.charAt(0).toUpperCase() + m.slice(1)])
const MARKER_RE = new RegExp(
  '(?<![' + NL + '])((?:' + MARKERS_CASED.map(escapeRe).join('|') + ')[ \\t]+)(' + CAPWORD + '(?:[ \\t]+' + CAPWORD + '){0,2})',
  'g'
)

// Слой 4: отчества.
const PATRONYMIC_RE = new RegExp(
  '(?<![' + NL + '])[А-ЯЁ][а-яё]+(?:ович|евич|ьевич|ич|овна|евна|ьевна|инична|ична)(?![' + NL + '])',
  'g'
)

// Слой 5: фамилии по суффиксам — ТОЛЬКО в середине предложения (lookbehind: перед
// словом стоит обычный символ + пробел, т.е. не начало предложения/кавычка/скобка).
const SURNAME_SUFFIX = '(?:ов|ова|ев|ева|ёв|ёва|ин|ина|ын|ына|ский|ская|цкий|цкая|ской|енко|ук|юк|чук|ян|янц|швили|дзе|оглы|оглу|заде|улы|кызы|их|ых)'
const SURNAME_RE = new RegExp(
  '(?<=[^.!?:;\\n«»"()\\[\\]]\\s)[А-ЯЁ][а-яё]+' + SURNAME_SUFFIX + '(?![' + NL + '])',
  'g'
)

// Контакты.
const EMAIL_RE = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g
const URL_RE = /https?:\/\/[^\s]+/gi
const SOCIAL_RE = /\b(?:t\.me|vk\.com|vk\.ru|instagram\.com|wa\.me|youtube\.com|youtu\.be|tiktok\.com|ok\.ru)\/[^\s]+/gi
const PHONE_RE = /(?<!\d)(?:\+7|8|7)[\s\-]?\(?\d{3}\)?[\s\-]?\d{3}[\s\-]?\d{2}[\s\-]?\d{2}(?!\d)/g
const HANDLE_RE = /(^|[\s(])@[A-Za-z0-9_.]{2,}/g

const LABEL: Record<string, string> = {
  name: 'ИМЯ', patronymic: 'ОТЧЕСТВО', surname: 'ФАМИЛИЯ',
  phone: 'ТЕЛЕФОН', email: 'ПОЧТА', handle: 'КОНТАКТ',
}

export function anonymize(text: string, opts?: { extraNames?: string[] }): { masked: string; map: AnonMap } {
  if (!text || typeof text !== 'string') return { masked: text, map: {} }
  const map: AnonMap = {}
  const counters: Record<string, number> = {}

  const put = (kind: string, value: string): string => {
    const found = Object.entries(map).find(([, v]) => v === value)
    if (found) return found[0]
    counters[kind] = (counters[kind] || 0) + 1
    const ph = `[${LABEL[kind]}-${counters[kind]}]`
    map[ph] = value
    return ph
  }

  let s = text
  // 1) Контакты (надёжно).
  s = s.replace(EMAIL_RE, m => put('email', m))
  s = s.replace(URL_RE, m => put('handle', m))
  s = s.replace(SOCIAL_RE, m => put('handle', m))
  s = s.replace(PHONE_RE, m => put('phone', m))
  s = s.replace(HANDLE_RE, (m, pre) => pre + put('handle', m.slice(pre.length)))

  // 1.5) ИЗВЕСТНЫЕ имена из профиля (имя психолога) — маскируем ГАРАНТИРОВАННО
  // везде, даже в кавычках и без маркера. Только с заглавной (нарицательные не трогаем).
  const extra = (opts?.extraNames ?? []).flatMap(n => (n || '').split(/\s+/)).map(t => t.trim()).filter(t => t.length >= 2)
  if (extra.length) {
    const stems = Array.from(new Set(extra.map(nameStem))).filter(x => x.length >= 2).sort((a, b) => b.length - a.length)
    const re = new RegExp('(?<![' + NL + '])(' + stems.map(escapeRe).join('|') + ')[а-яё]{0,3}(?![' + NL + '])', 'g')
    s = s.replace(re, m => (/^[А-ЯЁ]/.test(m) ? put('name', m) : m))
  }

  // 2) Имена по маркеру (ловит редкие имена без словаря). Маркер сохраняем.
  s = s.replace(MARKER_RE, (_m, pre, nm) => pre + put('name', nm))

  // 3) Имена по словарю (+ отчество/фамилия следом).
  s = s.replace(NAME_RE, m => (/^[А-ЯЁ]/.test(m) ? put('name', m) : m))

  // 4) Отчества (по суффиксам).
  s = s.replace(PATRONYMIC_RE, m => put('patronymic', m))

  // 5) Фамилии по суффиксам — только в середине предложения.
  s = s.replace(SURNAME_RE, m => put('surname', m))

  return { masked: s, map }
}

export function deanonymize(text: string, map: AnonMap): string {
  if (!text || !map) return text
  let out = text
  // от длинных плейсхолдеров к коротким, чтобы [ИМЯ-1] не задел [ИМЯ-10]
  for (const ph of Object.keys(map).sort((a, b) => b.length - a.length)) {
    out = out.split(ph).join(map[ph])
  }
  return out
}

// Для потока: вернуть восстановленный текст, придержав недописанную заглушку в конце.
export function safeRestoredPrefix(maskedSoFar: string, map: AnonMap): string {
  const restored = deanonymize(maskedSoFar, map)
  const lastOpen = restored.lastIndexOf('[')
  if (lastOpen === -1) return restored
  const closeAfter = restored.indexOf(']', lastOpen)
  if (closeAfter === -1) return restored.slice(0, lastOpen)
  return restored
}
