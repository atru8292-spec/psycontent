// Серверный отказ (lib/energy.ts canConsume) берет LIMIT_REFUSAL отсюда же, чтобы экран и сервер не расходились.

export type Materials = { remaining: number; cap: number; kind: 'trial' | 'month' }

export function plural(n: number, one: string, few: string, many: string): string {
  const m10 = n % 10, m100 = n % 100
  if (m10 === 1 && m100 !== 11) return one
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few
  return many
}

export function isMaterials(v: any): v is Materials {
  return !!v && typeof v.remaining === 'number' && typeof v.cap === 'number' && (v.kind === 'trial' || v.kind === 'month')
}

const trialWord = (n: number) => plural(n, 'пробный текст', 'пробных текста', 'пробных текстов')

// Пилюля (старое меню) и подпись для чтения с экрана
export const pillText = (m: Materials) => `${m.remaining} из ${m.cap}`
export const pillAria = (m: Materials) => m.kind === 'trial'
  ? `Пробных текстов осталось: ${m.remaining} из ${m.cap}`
  : `Текстов на этот месяц осталось: ${m.remaining} из ${m.cap}`

// Остаток внизу меню на компьютере (вариант А): «Осталось 3 из 10 пробных текстов», «Осталось 38 из 50 до 17 декабря».
// until: дата конца оплаченного месяца словами («17 декабря»), если известна
export const leftLine = (m: Materials, until?: string) => m.remaining <= 0
  ? (m.kind === 'trial' ? END.trial.short : END.month.title())
  : m.kind === 'trial'
  ? `Осталось ${m.remaining} из ${m.cap} пробных текстов`
  : `Осталось ${m.remaining} из ${m.cap}${until ? ` до ${until}` : ' в этом месяце'}`

// Строка в Настройках над тарифами («из N текстов» не склоняется: после «из 10» всегда «текстов»)
export const profileLine = (m: Materials) => m.remaining <= 0
  ? (m.kind === 'trial' ? END.trial.title(m.cap) : END.month.title())
  : m.kind === 'trial'
  ? `Осталось ${m.remaining} из ${m.cap} пробных текстов. Срока у них нет`
  : `В этом месяце осталось ${m.remaining} из ${m.cap} текстов`

// Строка под главной кнопкой «Написать» (решение Арины 17.11: на телефоне всегда, на компьютере рядом с кнопкой).
// n: сколько текстов спишет нажатие (число выбранных форматов). Счет честный: пост и карусель это 2 текста.
//   первый день пробного:   «Это 2 из 10 пробных текстов»
//   дальше пробный:         «После этого останется 1 пробный текст», в конце «Это последний пробный текст»
//   платный:                «Останется 36 из 50 до 12 декабря» (без даты «... в этом месяце»)
//   выбрано больше остатка: «Осталось 1 пробный текст, убери лишние форматы»
export function spendLine(m: Materials, n: number, until?: string): string {
  if (n <= 0 || m.remaining <= 0) return ''
  if (n > m.remaining) {
    return m.kind === 'trial'
      ? `Осталось ${m.remaining} ${trialWord(m.remaining)}, убери лишние форматы`
      : `Осталось ${m.remaining} из ${m.cap}, убери лишние форматы`
  }
  const after = m.remaining - n
  if (m.kind === 'month') return `Останется ${after} из ${m.cap}${until ? ` до ${until}` : ' в этом месяце'}`
  if (m.remaining === m.cap) return `Это ${n} из ${m.cap} пробных текстов`
  if (after === 0) return n === 1 ? 'Это последний пробный текст' : 'Это последние пробные тексты'
  return `После этого останется ${after} ${trialWord(after)}`
}

// Старая подсказка под кнопкой (пробных осталось 1-2). «Написать» теперь показывает spendLine, оставлено для совместимости
export const lowHint = (m: Materials) => {
  if (m.kind !== 'trial') return ''
  if (m.remaining === 1) return 'Это последний пробный текст'
  if (m.remaining === 2) return `Осталось два пробных текста из ${m.cap}`
  return ''
}

