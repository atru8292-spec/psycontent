import { NextRequest, NextResponse } from 'next/server'
import { createClient } from '@supabase/supabase-js'
import { generateWithAI } from '@/lib/openrouter'

const supabaseAdmin = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL!,
  process.env.SUPABASE_SERVICE_ROLE_KEY!
)

const SYSTEM_PROMPT = `Ты — бренд-стратег с 15-летним опытом создания позиционирования для психологов и помогающих специалистов. Ты объединяешь знания из брендинга (фреймворки Саймона Синека, StoryBrand Миллера, архетипы Юнга, модель тона голоса Nielsen Norman Group) и глубокое понимание психотерапевтической практики.

ТВОЯ ЗАДАЧА:
Создать детальный, персонализированный "Паспорт бренда" для психолога на основе его данных распаковки. Паспорт должен быть готовым руководством к действию — не абстрактным, а конкретным.

ПРИНЦИПЫ:
1. АУТЕНТИЧНОСТЬ — всё должно отражать реального человека, а не шаблонного "психолога из интернета"
2. СПЕЦИФИЧНОСТЬ — избегай общих фраз. Вместо "помогаю людям" пиши конкретно кому и с чем
3. УЧИТЫВАЙ ПОДХОД — это КРИТИЧЕСКИ важно для тона:
   - КПТ: структурный, логичный, научный, практичный, с конкретными техниками
   - Гештальт: философский, про чувства и осознанность, вопрошающий, парадоксальный
   - Психоанализ: глубокий, символический, метафоричный, исследующий бессознательное
   - Экзистенциальный: про смысл, свободу, ответственность, аутентичность
   - Системный семейный: про паттерны, взаимосвязи, циклы в отношениях
   - Арт-терапия: творческий, образный, безоценочный, символический
   - Интегративный: гибкий, адаптивный, берущий лучшее из разных подходов
4. ПРАКТИЧНОСТЬ — каждый элемент должен быть применим сразу
5. ЭТИЧНОСТЬ — никаких гарантий результата ("вылечу", "гарантирую"), никаких диагнозов, уважение конфиденциальности

КАТЕГОРИЧЕСКИ ИЗБЕГАЙ ШАБЛОННЫХ ФРАЗ:
- "путешествие к себе"
- "целительное пространство"
- "обрести внутреннюю гармонию"
- "помощь в преодолении жизненных трудностей"
- "квалифицированная психологическая помощь"
- "индивидуальный подход к каждому"
- "безопасное пространство для исцеления"
Вместо этого — конкретные, живые, узнаваемые формулировки.

ФОРМАТ:
- Пиши на русском языке
- Используй заголовки с ##
- Используй списки с -
- Будь конкретен: давай готовые тексты, а не рекомендации
- Каждый раздел — 200-400 слов`

export async function POST(request: NextRequest) {
  try {
    const { userId } = await request.json()

    if (!userId) {
      return NextResponse.json({ error: 'userId required' }, { status: 400 })
    }

    const { data: profile, error: profileError } = await supabaseAdmin
      .from('onboarding_profiles')
      .select('*')
      .eq('user_id', userId)
      .single()

    if (profileError || !profile) {
      console.error('Profile error:', profileError)
      return NextResponse.json({ error: 'Profile not found' }, { status: 404 })
    }

    const userPrompt = `Вот данные распаковки психолога:

ИМЯ: ${profile.full_name}
ПОДХОД: ${(profile.approach || []).join(', ')}
НИША (с чем работает): ${(profile.niche || []).join(', ')}
ОПЫТ: ${profile.experience}
ТОН ОБЩЕНИЯ: ${profile.tone}
ЦЕННОСТИ: ${profile.values_text || 'не указаны'}
ЧТО БЕСИТ В ИНДУСТРИИ: ${profile.what_annoys || 'не указано'}
ПОДПИСЧИКОВ: ${profile.current_followers || 'не указано'}
ПЛОЩАДКИ: ${(profile.platforms || []).join(', ')}
КЛИЕНТОВ В МЕСЯЦ: ${profile.current_clients}
ИСТОЧНИК КЛИЕНТОВ: ${profile.client_source || 'не указан'}
ГЛАВНАЯ БОЛЬ С КОНТЕНТОМ: ${profile.biggest_pain || 'не указана'}
ЦЕЛЬ НА 3 МЕСЯЦА: ${profile.goal}
ВРЕМЯ НА КОНТЕНТ: ${profile.time_available || 'не указано'}
МЕЧТА О БЛОГЕ: ${profile.dream_blog || 'не указана'}

Создай ПОЛНЫЙ ПАСПОРТ БРЕНДА по следующей структуре:

## 1. Миссия
Почему этот психолог делает то, что делает. 2-3 предложения, от сердца, не шаблонно. Используй фреймворк Синека (начни с "Почему").

## 2. Позиционирование
Формула: "Я помогаю [конкретно кому] [с какой конкретной проблемой] через [какой подход/метод], чтобы они [конкретный результат]"
+ развёрнутое описание на 3-4 предложения.

## 3. Архетип бренда
Определи 1 основной + 1 дополнительный архетип из 12 юнгианских (Мудрец, Заботливый, Маг, Герой, Искатель, Творец, Правитель, Бунтарь, Шут, Любовник, Славный малый, Ребёнок). Объясни почему именно эти. Как это проявляется в контенте.

## 4. Тон голоса
Опиши по 4 измерениям Nielsen Norman Group:
- Формальность (от разговорного до академического) — где этот психолог? + пример фразы
- Серьёзность (от лёгкого до серьёзного) — где? + пример фразы
- Дерзость (от уважительного до провокационного) — где? + пример фразы
- Энтузиазм (от сдержанного до энергичного) — где? + пример фразы
+ 5 слов/фраз которые этот психолог ИСПОЛЬЗУЕТ в текстах
+ 5 слов/фраз которые он НЕ использует никогда

## 5. Аватар идеального клиента
Опиши как реального человека:
- Имя, возраст, профессия, семейная ситуация
- Что болит (поверхностные боли — симптомы)
- Чего боится (глубокие страхи)
- О чём мечтает
- Что триггерит обращение к психологу
- Как ищет психолога, что важно при выборе
- Какой контент его зацепит в ленте

## 6. Уникальное ценностное предложение (УТП)
3 конкретных пункта: чем этот психолог отличается от тысяч других. Не "индивидуальный подход", а реальные, ощутимые отличия.

## 7. Био для Instagram
2 варианта готового текста для шапки профиля (до 150 символов каждый). С эмодзи. Конкретный. Сразу понятно — для кого и зачем.

## 8. Описание для Telegram-канала
2 варианта готового текста (4-5 строк каждый). Тёплый, личный, объясняющий что здесь будет и для кого.

## 9. Контентные столбы (5 рубрик)
Для каждой рубрики:
- Название рубрики
- Описание (2 предложения)
- 5 конкретных тем постов
- Рекомендуемый формат (текстовый пост / карусель / рилс / сторис)

## 10. Ключевые сообщения бренда
5 фраз-мантр, которые этот психолог повторяет регулярно. Узнаваемые, запоминающиеся, отражающие его позицию.

## 11. Стоп-темы и этические границы
5 тем, о которых НЕ стоит писать. С учётом подхода, этики и позиционирования. Для каждой — объяснение почему.

## 12. Голос бренда в действии
Напиши 3 ПОЛНЫХ примера первых абзацев постов (по 4-5 предложений каждый):
- Один психообразовательный (объясняет что-то из ниши)
- Один личный/рефлексивный (делится мыслями)
- Один мягко-продающий (приглашает к работе)
Каждый должен начинаться с цепляющего хука. Каждый должен звучать в тоне этого конкретного психолога.`

    const result = await generateWithAI(SYSTEM_PROMPT, userPrompt)

    const { error: saveError } = await supabaseAdmin
      .from('brand_passports')
      .upsert({
        user_id: userId,
        content: result,
        generated_at: new Date().toISOString(),
      }, {
        onConflict: 'user_id'
      })

    if (saveError) {
      console.error('Save error:', saveError)
    }

    return NextResponse.json({ passport: result })

  } catch (error: any) {
    console.error('Generate error:', error)
    return NextResponse.json({ error: error.message }, { status: 500 })
  }
}
