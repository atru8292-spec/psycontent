function getFormatInstruction(format: string): string {
  if (format === 'post') {
    return `ФОРМАТ: Текстовый пост
- Короткие абзацы (1-3 строки). Много воздуха.
- Рваный ритм: короткое. Длиннее. Снова короткое.
- Длина: 800-1500 символов.`
  }
  if (format === 'stories') {
    return `ФОРМАТ: Сторис (5-7 экранов)
- Каждый экран = 5 секунд чтения максимум
- Экран 1: вопрос или опрос
- Экраны 2-5: по одной мысли
- Экран 6: инсайт
- Экран 7: CTA
- Пиши ОЧЕНЬ коротко
- Обязательно помечай [Экран 1], [Экран 2] и т.д.`
  }
  // По умолчанию — пост
  return `ФОРМАТ: Текстовый пост
- Короткие абзацы (1-3 строки). Много воздуха.
- Рваный ритм: короткое. Длиннее. Снова короткое.
- Длина: 800-1500 символов.`
}

