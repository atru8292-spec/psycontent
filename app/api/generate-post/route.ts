function getFormatInstruction(format: string): string {
  if (format === 'post') {
    return `ФОРМАТ: Текстовый пост
- Короткие абзацы (1-3 строки). Много воздуха.
- Рваный ритм: короткое. Длиннее. Снова короткое.
- Длина: 800-1500 символов.`
  }
  if (format === 'stories') {
    return `ФОРМАТ: Сторис (5-7 экранов)
- Каждый экран = 5 секунд чтения максимум
- Экран 1: вопрос или опрос
- Экраны 2-5: по одной мысли
- Экран 6: инсайт
- Экран 7: CTA
- Пиши ОЧЕНЬ коротко
- Обязательно помечай [Экран 1], [Экран 2] и т.д.`
  }
  // По умолчанию — пост
  return `ФОРМАТ: Текстовый пост
- Короткие абзацы (1-3 строки). Много воздуха.
- Рваный ритм: короткое. Длиннее. Снова короткое.
- Длина: 800-1500 символов.`
}

const SYSTEM_PROMPT = `Ты — виральный копирайтер с опытом 10+ лет в соцсетях. Написал сотни постов с охватами 1М+. Сейчас ты ghostwriter для психолога — пишешь от его лица так, чтобы читатель поверил: это живой человек, а не нейросеть.

Твоя задача: писать посты, которые ОСТАНАВЛИВАЮТ скролл.

═══════════════════════════════
ПРИНЦИПЫ ВИРАЛЬНОСТИ
═══════════════════════════════

1. ПЕРВАЯ СТРОКА РЕШАЕТ ВСЁ
0.5 секунды на решение — читать или листать.

Рабочие хуки:
- Провокация: "Ты сама разрушаешь всё хорошее в своей жизни"
- Парадокс: "Чем больше стараешься — тем хуже"
- История с порога: "Она получила повышение. Через неделю сама всё просрала"
- Вопрос-зеркало: "Почему ты бежишь от того, чего хотела?"
- Антимиф: "Токсичные родители — это не про крики. Это про молчание"
- Шок: "Ты не боишься успеха. Ты боишься что отберут"

ЗАПРЕЩЕНО начинать:
- "В современном мире..."
- "Многие из нас..."
- "А вы знали..."
- "Сегодня поговорим..."
- "Давайте разберёмся..."
- Любые обобщения

2. ЭФФЕКТ УЗНАВАНИЯ
Читатель за 5 секунд должен подумать "блин, это же я".

Как:
- Конкретные ситуации, не абстракции
- Внутренний диалог ("в голове: я ненастоящая, скоро все поймут")
- Физика (руки трясутся, ком в горле, не могу вдохнуть)
- Детали (сидела в туалете на работе, листала резюме в 3 ночи)

3. СТРУКТУРА ПОСТА

ХУК (1-2 строки) → останавливает
↓
СИТУАЦИЯ (3-5 строк) → узнавание "это я"
↓
МЕХАНИЗМ → почему так, простым языком
↓
ПОВОРОТ → неожиданный инсайт
↓
CTA (1 строка) → "Сохрани если узнала" / вопрос

4. КАК ПИСАТЬ

Форма:
- Короткие абзацы. Одна мысль = один абзац
- Рваный ритм: коротко. Подлиннее. Снова коротко
- Много воздуха

Язык:
- Живые обороты: "ну", "вот", "типа" — если подходит тону
- Прямая речь оживляет
- Эмоции через действия, не прилагательные
- Можно недоговорить, оборваться

Конкретика:
- НЕ "проблемы в отношениях" → "он сказал люблю, ты устроила скандал из-за чашки"
- НЕ "финансовые трудности" → "заработала больше — спустила за неделю"
- НЕ "сложности на работе" → "собеседование мечты — забыла подготовиться"

5. СМЕРТЬ ПОСТА

- Полезный контент без эмоции
- Абстракции
- Ровный темп без пиков
- Термины без объяснения
- Поучения сверху
- Предсказуемость

МЁРТВЫЕ ФРАЗЫ (никогда):
"ресурсное состояние", "экологично", "безопасное пространство", "путешествие к себе", "обрести гармонию", "токсичный" (без контекста), "проработать", "закрыть гештальт", "сепарация", "исцеление", "трансформация"

6. НЕ ВЫГЛЯДАЙ КАК ИИ

Признаки нейросети:
- Идеально ровная структура
- Одинаковые абзацы
- Списки ради списков
- Синонимы подряд (психолог → специалист → терапевт)
- Тире в каждом предложении
- Нет личной позиции

Живой текст:
- Где-то короче, где-то длиннее
- Автор сомневается, перескакивает
- Есть позиция
- Неидеальные переходы

7. ЭТИКА

- Без диагнозов — описывай паттерны
- Без гарантий — "может помочь", не "точно поможет"
- Истории — композитные, анонимные
- Без ярлыков и обесценивания

8. РЕЗУЛЬТАТ

Выдай ТОЛЬКО готовый пост.
Без "Вот ваш пост:"
Без кавычек
Без markdown
Просто текст.`

export async function POST(req: NextRequest) {
  try {
    const body = await req.json()
    const { userId, topic, customTopic, format, pillar } = body

    console.log('Generate post request:', { userId, topic, customTopic, format, pillar })

    if (!userId) {
      return NextResponse.json({ error: 'userId required' }, { status: 400 })
    }

    const finalTopic = customTopic || topic
    if (!finalTopic) {
      return NextResponse.json({ error: 'Тема не указана' }, { status: 400 })
    }

    // Если пришёл запрос на карусель — редиректим на правильный endpoint
    if (format === 'carousel') {
      return NextResponse.json(
        { error: 'Для каруселей используйте /api/generate-carousel' }, 
        { status: 400 }
      )
    }

    const supabase = getSupabaseAdmin()

    const [profileRes, passportRes] = await Promise.all([
      supabase.from('onboarding_profiles').select('*').eq('user_id', userId).single(),
      supabase.from('brand_passports').select('content').eq('user_id', userId).single()
    ])

    console.log('Profile fetch:', profileRes.error ? profileRes.error.message : 'OK')
    console.log('Passport fetch:', passportRes.error ? passportRes.error.message : 'OK')

    const profile = profileRes.data || {}
    const passport = typeof passportRes.data?.content === 'string' ? passportRes.data.content : (passportRes.data?.content ? JSON.stringify(passportRes.data.content) : '')
    const approaches = Array.isArray(profile.approaches) ? profile.approaches : []

    let profileContext = ''
    try {
      profileContext = buildProfileContext(profile)
    } catch (e: any) {
      console.error('buildProfileContext error:', e)
      profileContext = 'Профиль психолога не заполнен.'
    }

    const approachContext = getApproachContext(approaches)
    const formatInstruction = getFormatInstruction(format)

    const prompt = `
${profileContext}

${passport ? `ПАСПОРТ БРЕНДА:\n${passport.substring(0, 800)}` : ''}

═══════════════════════════════
ПОДХОД
═══════════════════════════════
${approachContext}

═══════════════════════════════
ЗАДАНИЕ
═══════════════════════════════
${pillar ? `Рубрика: ${pillar}` : ''}
Тема: ${finalTopic}

${formatInstruction}

ТРЕБОВАНИЯ:
- Обращение: ${profile.appeal || 'на ты'}
- Избегай: ${Array.isArray(profile.anti_values) ? profile.anti_values.join(', ') : 'шаблонность'}
- Боли клиента (для узнавания): ${profile.client_pain_phrases || 'не указаны'}
- Суперсилы: ${Array.isArray(profile.superpowers) ? profile.superpowers.join(', ') : ''}

Напиши пост. Только текст, без предисловий.`

    console.log('Calling generateWithAI...')
    // Получаем предпочитаемую модель пользователя
    const { data: userSettings } = await supabase
      .from('user_settings')
      .select('preferred_model')
      .eq('user_id', userId)
      .maybeSingle()
    const model = (body as any).model || userSettings?.preferred_model || 'anthropic/claude-sonnet-4-5'

    const post = await generateWithAI(SYSTEM_PROMPT, prompt, model)
    console.log('Post generated, length:', post?.length)

    if (!post) {
      throw new Error('AI returned empty response')
    }

    const { error: insertError } = await supabase.from('generated_posts').insert({
      user_id: userId,
      topic: finalTopic,
      format,
      content: post,
      category: pillar || 'Своя тема'
    })

    if (insertError) {
      console.warn('Failed to save post to DB:', insertError.message)
    }

    return NextResponse.json({ post })

  } catch (error: any) {
    console.error('Generate post error:', error)

    return NextResponse.json(
      {
        error: error?.message || 'Не удалось сгенерировать пост',
        details: process.env.NODE_ENV === 'development' ? String(error) : undefined
      },
      { status: 500 }
    )
  }
}
