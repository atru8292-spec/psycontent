function getFormatInstruction(format: string): string {
  if (format === 'post') {
    return `ФОРМАТ: Текстовый пост (Instagram/Telegram)
- Короткие абзацы (1-3 строки). Много воздуха между ними.
- Чередуй длину предложений: короткое. Потом длинное с деталями. Снова короткое.
- Общая длина: 150-400 слов для Instagram, до 800 для Telegram.`
  }
  if (format === 'carousel') {
    return `ФОРМАТ: Карусель (7-10 слайдов)
- [Слайд 1] Хук-заголовок. Не тема, а выгода или боль. Добавь "листай".
- [Слайд 2] Узнаваемая ситуация.
- [Слайды 3-7] По 1 тезису/шагу (2-3 предложения). Каждый слайд заканчивается микронезавершённостью.
- [Слайд 8-9] Вывод + мягкий CTA.
- Каждый слайд начинается с пометки [Слайд N].
- НЕ дублируй текст карусели в описании.`
  }
  if (format === 'stories') {
    return `ФОРМАТ: Сторис-цепочка (5-7 экранов)
- Каждый экран читается за 5 секунд максимум.
- Экран 1: вводная с опросом или вопросом.
- Экраны 2-5: развитие, по одной мысли.
- Экран 6: инсайт.
- Экран 7: CTA.
- Пиши ОЧЕНЬ коротко.`
  }
  return 'Текстовый пост.'
}

const SYSTEM_PROMPT = `Ты — копирайтер-призрак (ghostwriter) для практикующего психолога. Ты пишешь посты ОТ ЕГО ЛИЦА так, чтобы читатель поверил: это написал живой человек после рабочего дня, а не нейросеть.

═══════════════════════════════
ЖЕЛЕЗНЫЕ ПРАВИЛА (нарушение = провал)
═══════════════════════════════

1. НИКАКИХ МЁРТВЫХ ФРАЗ:
"путешествие к себе", "обрести гармонию", "безопасное пространство", "ресурсное состояние", "мне откликается", "экологично", "проявляться", "работа над собой" (без конкретики), "каждый из нас", "ни для кого не секрет", "как известно", "в современном мире"

2. НЕ ВЫГЛЯДАЙ КАК НЕЙРОСЕТЬ:
- Не начинай с глобального ("В современном мире...")
- Не используй равномерную плотность — делай смысловые пики и провалы
- Не ставь длинное тире в каждом предложении
- Не крути синонимическую карусель (психолог → специалист → терапевт)
- Не пиши идеально ровно — человек перескакивает, сомневается, оговаривается
- Допускай живые речевые обороты: "ну", "вот", "короче", "типа" (если это соответствует тону)

3. АРХИТЕКТУРА ПОСТА (ВОРОНКА):
- ХУК (первые 2-3 строки) — парадокс, боль, наблюдение, вопрос-зеркало, антимиф, шокирующий факт или история с порога. НЕ "А вы знали...", НЕ "В этом посте я расскажу..."
- ТЕЛО — механизм, история, инсайт. Конкретные примеры, не абстракции.
- ФИНАЛ — мягкий CTA без давления. НЕ "записывайтесь на консультацию". Лучше: вопрос, приглашение к размышлению, "сохрани если узнал себя"

4. ПИШИ В ТОЧНОМ ТОНЕ ПСИХОЛОГА:
- Обращайся так, как указано в профиле (ты/вы)
- Используй речевые привычки из "голоса бренда"
- Учитывай шкалы: формальность, серьёзность, осторожность
- Используй терминологию и метафоры подхода психолога

5. ИСПОЛЬЗУЙ АВАТАР КЛИЕНТА:
- Фразы боли клиента — вставляй в хуки и узнавалки
- Страхи клиента — валидируй их
- Результат мечты — показывай как возможный

6. ЭТИКА:
- Никаких диагнозов, гарантий исцеления, обесценивания
- Истории клиентов — только анонимные, композитные
- Не навешивай ярлыки ("ты созависимый")

7. РЕЗУЛЬТАТ:
- Выдай ТОЛЬКО готовый пост. Без предисловий, пояснений, заголовков типа "Вот ваш пост:"
- Не оборачивай в кавычки или markdown`

export async function POST(req: NextRequest) {
  try {
    const { userId, topic, customTopic, format, pillar } = await req.json()

    if (!userId) return NextResponse.json({ error: 'userId required' }, { status: 400 })

    const finalTopic = customTopic || topic
    if (!finalTopic) return NextResponse.json({ error: 'Тема не указана' }, { status: 400 })

    const supabase = getSupabaseAdmin()

    const [profileRes, passportRes] = await Promise.all([
      supabase.from('onboarding_profiles').select('*').eq('user_id', userId).single(),
      supabase.from('brand_passports').select('content').eq('user_id', userId).single()
    ])

    const profile = profileRes.data || {}
    const passport = passportRes.data?.content || ''
    const approaches = Array.isArray(profile.approaches) ? profile.approaches : []

    const profileContext = buildProfileContext(profile)
    const approachContext = getApproachContext(approaches)
    const formatInstruction = getFormatInstruction(format)

    const prompt = `
${profileContext}

${passport ? `ПАСПОРТ БРЕНДА (ключевые сообщения, позиционирование):\n${passport.substring(0, 800)}` : ''}

═══════════════════════════════
КОНТЕКСТ ПОДХОДА
═══════════════════════════════
${approachContext}

═══════════════════════════════
ЗАДАНИЕ
═══════════════════════════════
${pillar ? `Рубрика: ${pillar}` : ''}
Тема: ${finalTopic}

${formatInstruction}

ДОПОЛНИТЕЛЬНЫЕ ТРЕБОВАНИЯ:
- Обращение: ${profile.appeal || 'на вы'}
- Антиценности психолога (ИЗБЕГАЙ в тексте): ${Array.isArray(profile.anti_values) ? profile.anti_values.join(', ') : 'шаблонность'}
- Боли клиента (ИСПОЛЬЗУЙ для узнавания): ${profile.client_pain_phrases || 'не указаны'}
- Суперсилы психолога (ОПИРАЙСЯ): ${Array.isArray(profile.superpowers) ? profile.superpowers.join(', ') : ''}

Напиши пост. Только пост, без предисловий.`

    const post = await generateWithAI(SYSTEM_PROMPT, prompt)

    await supabase.from('generated_posts').insert({
      user_id: userId,
      topic: finalTopic,
      format,
      content: post,
      category: pillar || 'Своя тема'
    }).catch(() => {})

    return NextResponse.json({ post })
  } catch (error: any) {
    console.error('Generate post error:', error)
    return NextResponse.json({ error: 'Не удалось сгенерировать пост' }, { status: 500 })
  }
}
