import { NextRequest, NextResponse } from 'next/server'
import { createClient } from '@supabase/supabase-js'
import { generateWithAI } from '@/lib/openrouter'
import { buildProfileContext } from '@/lib/profile-context'

function getSupabaseAdmin() {
  return createClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.SUPABASE_SERVICE_ROLE_KEY!
  )
}

function getApproachRewriteStyle(approaches: string[]): string {
  const styles: Record<string, string> = {
    'КПТ': 'КПТ-стиль: структурность, цепочка мысль→эмоция→поведение, конкретные техники. Метафоры: "мысль — гипотеза", "мозг как баг-трекер".',
    'Психоанализ': 'Психоаналитический: глубина, многослойность, паузы. Фокус на бессознательном, детских паттернах, повторениях. Метафоры: "старая пьеса с новыми актерами".',
    'Гештальт': 'Гештальт: через ощущения и "здесь и сейчас". Вовлечение в опыт. Ритм прерывистый. Метафоры: "незаконченная мелодия", "прерванный контакт".',
    'Схема-терапия': 'Схема-терапия: режимы как персонажи (Критик, Ребёнок, Взрослый). Покажи откуда схема и как переписать. Метафоры: "программа на автопилоте".',
    'ACT': 'ACT: парадокс борьбы с болью. Фокус на ценностях. "Жить несмотря на боль, а не ждать когда пройдёт". Метафоры: "пассажиры в автобусе".',
    'Экзистенциальный': 'Экзистенциальный: философская глубина, большие вопросы, свобода и ответственность. Метафоры: "проект себя", "человек перед бездной".',
    'ЭФТ': 'ЭФТ: эмоции под поведением. За гневом — страх, за отстранённостью — боль. Метафоры: "танец пары", "деструктивный цикл".',
    'EMDR': 'EMDR: застрявшие воспоминания, переработка. Метафоры: "разморозка памяти", "дефрагментация".',
    'Нарративная терапия': 'Нарративный: экстернализация проблемы. "Тревога — не ты, а персонаж в твоей истории". Метафоры: "книга жизни", "автор и герой".',
    'Телесно-ориентированная': 'Телесный: через тело. Где живёт эмоция, как тело помнит. Метафоры: "панцирь", "тело как хранилище".',
    'Арт-терапия': 'Арт-терапия: творчество как язык. "Рука знает то, что ум не признаёт". Образы, цвета, символы.',
  }

  const parts: string[] = []
  for (const approach of approaches) {
    const key = Object.keys(styles).find(k =>
      approach.toLowerCase().includes(k.toLowerCase()) || k.toLowerCase().includes(approach.toLowerCase())
    )
    if (key) parts.push(styles[key])
  }

  return parts.length > 0 ? parts.join('\n') : 'Интегративный: гибко комбинируй стили, сохраняя авторский голос.'
}

const getFormatInstruction = (format: string) => {
  if (format === 'post') {
    return `ФОРМАТ: Текстовый пост (Instagram/Telegram)
- Короткие абзацы (1-3 строки). Много воздуха.
- Чередуй длину предложений.
- 150-400 слов для Instagram, до 800 для Telegram.`
  }
  if (format === 'carousel') {
    return `ФОРМАТ: Карусель (7-10 слайдов)
- [Слайд 1] Хук-заголовок + "листай"
- [Слайд 2] Узнаваемая ситуация
- [Слайды 3-7] По 1 тезису (2-3 предложения). Каждый заканчивается микронезавершённостью.
- [Слайд 8-9] Вывод + CTA
- Каждый слайд: [Слайд N]`
  }
  if (format === 'reels') {
    return `ФОРМАТ: Сценарий Reels (30-60 сек)
- [Кадр] описание что в кадре
- [Хук (0-3 сек)] первые слова
- [Суть (3-45 сек)] основной текст
- [CTA (конец)] финал
- 1 секунда = 2-3 слова. Не длинно.`
  }
  if (format === 'stories') {
    return `ФОРМАТ: Сторис-цепочка (5-7 экранов)
- Каждый экран читается за 5 секунд
- Экран 1: опрос или вопрос
- Экраны 2-5: развитие
- Экран 6: инсайт
- Экран 7: CTA`
  }
  return 'Текстовый пост.'
}

const getGoalInstruction = (goal: string) => {
  if (goal === 'clearer') {
    return `ЦЕЛЬ: СДЕЛАТЬ ПОНЯТНЕЕ
- Переведи с "психологического" на "человеческий"
- Убери термины → замени метафорами из жизни
- "Когнитивное искажение катастрофизации" → "Мозг рисует самый страшный сценарий"
- Каждое предложение должен понять человек без образования`
  }
  if (goal === 'engaging') {
    return `ЦЕЛЬ: МАКСИМАЛЬНОЕ ВОВЛЕЧЕНИЕ
- Добавь мощный хук в начало (парадокс, узнавалка, провокация)
- Читатель должен кивать: "это точно про меня!"
- Используй фразы боли клиента из аватара
- Короткие предложения. Ритм. Пауза. Удар.`
  }
  if (goal === 'expert') {
    return `ЦЕЛЬ: ПОКАЗАТЬ ЭКСПЕРТНОСТЬ
- Добавь глубины: ПОЧЕМУ так происходит
- Механизмы: работа мозга, защиты, детские паттерны
- Используй терминологию подхода но объясняй её
- Читатель должен подумать: "Этот специалист реально разбирается"`
  }
  if (goal === 'sales') {
    return `ЦЕЛЬ: МЯГКАЯ ПРОДАЖА
- В конце нативно подведи к терапии: "Это можно прорабатывать. Я работаю с такими запросами."
- Не давить. Не "запишитесь на консультацию!"
- Через ценность: покажи что понимаешь проблему → намекни что есть путь → пригласи
- CTA: "Если узнали себя — можно начать с этого в терапии"`
  }
  return 'Улучшить текст в целом.'
}

