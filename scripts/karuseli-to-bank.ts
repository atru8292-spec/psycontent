// текст слайда одной строкой: пометки [выделено: X] -> X, ник и стрелки внизу слайда убраны
function cleanSlide(raw: string): string {
  // скобки изнутри наружу и через перенос строки: выделение и «ответ на» остаются текстом,
  // описания картинок (фото, скриншот, рисунок) убираем
  let t = raw, prev = ''
  while (t !== prev) {
    prev = t
    t = t.replace(/\[([^\[\]]*)\]/g, (_m, inner: string) => {
      const v = inner.replace(/\s+/g, ' ').trim()
      if (/^выделено:/i.test(v)) return v.replace(/^выделено:\s*/i, '')
      if (/^ответ на/i.test(v)) return `(${v})`
      return ''
    })
  }
  return t.split('\n').map(l => l.trim())
    // служебные пометки расшифровки («> Примечание: …») и ник внизу слайда
    .filter(l => l && !/^>/.test(l) && !/^@[\w.]+\s*(→|->)?$/.test(l) && !/^(→|->|>)+$/.test(l))
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim()
}

function sections(md: string) {
  const out: { title: string; slides: string[] }[] = []
  for (const part of md.split(/^## /m).slice(1)) {
    const title = part.split('\n')[0].trim()
    const slides = part.split(/^### Слайд \d+[^\n]*\n/m).slice(1).map(cleanSlide).filter(Boolean)
    out.push({ title, slides })
  }
  return out
}

