// Тест обезличивания: города (с 15.11.2026) и прежние слои. Без сети и без модели: npx tsx scripts/test-anonymize.ts
import assert from 'node:assert/strict'
import { anonymize, deanonymize } from '../lib/anonymize'

const city = (t: string) => Object.entries(anonymize(t).map).filter(([k]) => k.startsWith('[ГОРОД')).map(([, v]) => v)
let n = 0
const has = (t: string, want: string[]) => { const got = city(t); assert.deepEqual(got.sort(), [...want].sort(), `«${t}»: ждали ${want.join(', ') || 'ничего'}, получили ${got.join(', ') || 'ничего'}`); n++ }

// падежи и разные типы названий
has('Я живу в Москве, а клиентка из Казани.', ['Москве', 'Казани'])
has('Переехала из Новосибирска в Санкт-Петербург.', ['Новосибирска', 'Санкт-Петербург'])
has('Работаю онлайн, сама в Нижнем Новгороде.', ['Нижнем Новгороде'])
has('Вчера вернулась из Ростова-на-Дону.', ['Ростова-на-Дону'])
has('Родители в Набережных Челнах, я в Перми.', ['Набережных Челнах', 'Перми'])
has('Летом в Сочи, зимой в Питере.', ['Сочи', 'Питере'])
has('Екатеринбург, Самара и Уфа давно в планах.', ['Екатеринбург', 'Самара', 'Уфа'])
has('Принимаю очно в Ярославле и Твери.', ['Ярославле', 'Твери'])
has('Подруга из Минска, сестра в Алматы, брат в Ташкенте.', ['Минска', 'Алматы', 'Ташкенте'])
has('Сейчас в Новом Уренгое, до этого в Петропавловске-Камчатском.', ['Новом Уренгое', 'Петропавловске-Камчатском'])
has('Мск или СПб, неважно.', ['Мск', 'СПб'])
// омонимы: только после предлога места
has('Курган на окраине поля зарос травой.', [])
has('Я выросла в Кургане.', ['Кургане'])
has('Орел сидел на ветке.', [])
has('Мы переехали из Орла.', ['Орла'])
has('Находка для меня это ее улыбка.', [])
has('Живу в Грозном.', ['Грозном'])
// не город: обычные слова и строчные
has('москва-река и самарские пробки тут ни при чем.', [])
has('Пермский период и казанский вокзал.', [])
has('Мама сказала: «Тула подождет».', ['Тула'])

// возврат: в ответе модели метки меняются обратно
const { masked, map } = anonymize('Клиентка Анна из Москвы, звонила с +7 999 123-45-67.')
assert.ok(!masked.includes('Москвы') && !masked.includes('Анна') && !masked.includes('999'), masked)
assert.equal(deanonymize(masked, map), 'Клиентка Анна из Москвы, звонила с +7 999 123-45-67.')
n++
// имя психолога из профиля маскируется и рядом с городом
const r = anonymize('Меня зовут Арина, я психолог из Барнаула.', { extraNames: ['Арина'] })
assert.ok(!r.masked.includes('Арина') && !r.masked.includes('Барнаула'), r.masked)
n++
// фамилии, похожие на формы городов, без предлога не трогаем; город после предлога маскируем
has('Иванова сказала, что приедет.', [])
has('Мы жили в Иванове и в Череповце, потом в Чебоксарах.', ['Иванове', 'Череповце', 'Чебоксарах'])
has('Вернулась из Ростова.', ['Ростова'])
// служебные метки промптов городом не считаются
has('Речь: Подпись: Текст на экране: Слайд 1:', [])

console.log(`ok: обезличивание, ${n} проверок (города в падежах, омонимы, возврат, имя психолога)`)
