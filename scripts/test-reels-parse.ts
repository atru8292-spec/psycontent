// Проверка разбора рилса для экрана результата (lib/reels-parse.ts), без модели и сети:
// ~/.npm/_npx/*/node_modules/.bin/tsx scripts/test-reels-parse.ts
// 1) роли сценки с уточнением через запятую («Я, обычная реакция:») и их ключ для сдвига;
// 2) обычная фраза с двоеточием ролью не становится (вне «Речи», в монологе, «Ну, знаешь что:»);
// 3) надпись на видео отдельно, в копию текста не идет; у беззвучного рилса копия как раньше;
// 4) старые материалы (А:/Б:, «Экран N:», «Кадр:», «Мама (тихо):») разбираются как раньше.
import assert from 'node:assert/strict'
import { parse, reelsSpeech, roleKey, splitRole, overlayOf, screenGroups } from '../lib/reels-parse'

const ELENA = `Текст на экране: Вы отказали. Мама уже плохая мать.
Речь:
Я: Мам, я в воскресенье не приеду.
Мама: Конечно. Я же плохая мать, зачем ко мне приезжать.
Я, обычная реакция: Мам, ну при чем тут плохая мать? Я просто дома побыть хочу.
Я, после роликов про бережное общение: Мам, мне очень жаль, что ты так себя чувствуешь. Я благодарна тебе за все. Блядь, ладно, приеду.
Я: Мам, я в воскресенье не приеду.
Подпись: Собиралась отдохнуть дома. Теперь еду доказывать, что мама хорошая.`

const ZAHAR = `Текст на экране: «Успокойся». Охуенный способ помочь.
Речь: «Да успокойся ты уже». А ты до этой фразы вообще говорил спокойно. Ты попросил ее убрать телефон, потому что рассказываешь, как прошел день, а она третий раз спрашивает: «Что?» Ты повторил.
Подпись: Особенно прекрасно это «сразу завелся», когда ты уже несколько раз попросил об одном и том же.`

const BEZ = `Текст на экране: Коллега третий раз перебил тебя.
[смена]
Дома она спросила: «Ты будешь ужинать?»
Подпись: Сдерживался весь день.`

const STARY = `Кадр: кухня, вечер
Текст на экране: Когда мама звонит в десятый раз
А (раздраженно): Мам, я на работе.
Б: Я только спросить, ты поела?
Экран 2: Она правда только спросить
Рисую: стрелка от тревоги к звонку
Подпись: Знакомо?`

let n = 0
const ok = (name: string, fn: () => void) => { fn(); n++; console.log('ok', name) }

ok('роли Елены', () => {
  const roles = parse(ELENA, 'reels_scenka').filter(l => l.role).map(l => l.role)
  assert.deepEqual(roles, ['Я', 'Мама', 'Я, обычная реакция', 'Я, после роликов про бережное общение', 'Я'])
  const l = parse(ELENA, 'reels_scenka').find(x => x.role === 'Я, обычная реакция')!
  assert.equal(l.text, 'Мам, ну при чем тут плохая мать? Я просто дома побыть хочу.')
})
ok('ключ роли без уточнения', () => {
  assert.equal(roleKey('Я, обычная реакция'), 'Я')
  assert.equal(roleKey('Я, после роликов про бережное общение'), 'Я')
  assert.equal(roleKey('Мама (тихо)'), 'Мама')
  assert.equal(roleKey('Внутренний голос'), 'Внутренний голос')
  assert.deepEqual(splitRole('Я, обычная реакция'), ['Я,', 'обычная реакция'])
  assert.deepEqual(splitRole('Мама (тихо)'), ['Мама (тихо)', ''])
})
ok('копия Елены с уточнениями, без надписи и подписи', () => {
  assert.equal(reelsSpeech(ELENA, 'reels_scenka'), [
    'Я: Мам, я в воскресенье не приеду.',
    'Мама: Конечно. Я же плохая мать, зачем ко мне приезжать.',
    'Я, обычная реакция: Мам, ну при чем тут плохая мать? Я просто дома побыть хочу.',
    'Я, после роликов про бережное общение: Мам, мне очень жаль, что ты так себя чувствуешь. Я благодарна тебе за все. Блядь, ладно, приеду.',
    'Я: Мам, я в воскресенье не приеду.',
  ].join('\n'))
})
ok('надпись на видео', () => {
  assert.deepEqual(overlayOf(parse(ELENA, 'reels_scenka')), ['Вы отказали. Мама уже плохая мать.'])
  assert.deepEqual(overlayOf(parse(ZAHAR, 'reels_monolog')), ['«Успокойся». Охуенный способ помочь.'])
})
ok('монолог Захара: роли не ищутся, копия только речь', () => {
  assert.equal(parse(ZAHAR, 'reels_monolog').filter(l => l.role).length, 0)
  assert.equal(reelsSpeech(ZAHAR, 'reels_monolog').startsWith('«Да успокойся ты уже».'), true)
  assert.equal(reelsSpeech(ZAHAR, 'reels_monolog').includes('Охуенный способ'), false)
  assert.equal(reelsSpeech(ZAHAR, 'reels_monolog').includes('сразу завелся'), false)
})
ok('обычная фраза с двоеточием не роль', () => {
  const t = 'Текст на экране: Ну, знаешь что: ничего\nРечь:\nЯ: Привет.\nНу, знаешь что: так нельзя.\nОна сказала мне вчера вечером очень тихо: уйди.\nЯ, как обычно, в ответ промолчала и пошла на кухню ставить чайник: хватит.'
  const lines = parse(t, 'reels_scenka')
  assert.equal(lines.find(l => l.label === 'Текст на экране')!.role, undefined)
  assert.equal(lines.filter(l => l.role).map(l => l.role).join('|'), 'Я')
  // в сценке вне блока «Речь» и не в сценке ролей нет
  assert.equal(parse('Я, обычная реакция: текст', 'reels_monolog').filter(l => l.role).length, 0)
  assert.equal(parse('Кадр: кухня\nЯ, обычная реакция: текст\nРечь:\nЯ: да', 'reels_scenka').filter(l => l.role).length, 1)
})
ok('беззвучный рилс как раньше', () => {
  assert.equal(reelsSpeech(BEZ, 'reels_bez_slov'), 'Коллега третий раз перебил тебя.\n\nДома она спросила: «Ты будешь ужинать?»')
  assert.equal(screenGroups(parse(BEZ, 'reels_bez_slov'))!.length, 2)
})
ok('старые материалы', () => {
  const lines = parse(STARY, 'reels_scenka')
  assert.deepEqual(lines.filter(l => l.role).map(l => l.role), ['А (раздраженно)', 'Б'])
  assert.equal(lines.find(l => l.label === 'Кадр')!.text, 'кухня, вечер')
  assert.equal(lines.find(l => l.label === 'Экран 2')!.text, 'Она правда только спросить')
  assert.equal(reelsSpeech(STARY, 'reels_scenka'), 'А (раздраженно): Мам, я на работе.\nБ: Я только спросить, ты поела?\nОна правда только спросить')
  const t2 = 'Речь:\nМама (тихо): Ты поела?\nЯ: Да.\nВнутренний голос: Врешь.'
  assert.deepEqual(parse(t2, 'reels_scenka').filter(l => l.role).map(l => l.role), ['Мама (тихо)', 'Я', 'Внутренний голос'])
})
console.log(`все ${n} проверок прошли`)
